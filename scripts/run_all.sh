#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mkdir -p "$ROOT/simulation/build" "$ROOT/simulation/results" "$ROOT/simulation/vcd"

run_test() {
  local name="$1"; shift
  iverilog -g2012 -Wall -s "$name" -o "$ROOT/simulation/build/$name.out" "$@"
  pushd "$ROOT" >/dev/null
  vvp "$ROOT/simulation/build/$name.out" | sed '/\$finish called at/d' | tee "$ROOT/simulation/results/$name.log"
  popd >/dev/null
}

run_test tb_alu "$ROOT/rtl/alu.sv" "$ROOT/assertions/design_assertions.sv" "$ROOT/testbench/tb_alu.sv"
run_test tb_parameterized_alu "$ROOT/rtl/alu.sv" "$ROOT/testbench/tb_parameterized_alu.sv"
run_test tb_memory "$ROOT/rtl/memory.sv" "$ROOT/testbench/tb_memory.sv"
run_test tb_systemverilog "$ROOT/rtl/sequential_sv.sv" "$ROOT/rtl/traffic_light_sv.sv" "$ROOT/assertions/design_assertions.sv" "$ROOT/testbench/tb_systemverilog.sv"

echo "All Task 3 testbenches passed. VCD traces are generated by each testbench."
